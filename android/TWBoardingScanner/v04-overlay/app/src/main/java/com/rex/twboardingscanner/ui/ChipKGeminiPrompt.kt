package com.rex.twboardingscanner.ui

/** Prompt only analyses visible evidence; invisible data must never be guessed. */
object ChipKGeminiPrompt {
    fun forStock(code: String): String {
        require(code.matches(Regex("[0-9]{4,6}"))) { "Stock code must be 4-6 digits" }
        return """
你是台灣股市籌碼與技術面研究助理。以下圖片由使用者在「股市籌碼K線」App 中自行授權擷取，分析股票代號 $code。

【資料查核】
1. 先核對畫面中的股號及股名；如果不是 $code，先提出警告。
2. 註明畫面顯示的日期或時間，並將「畫面可見事實」和「你的推論」分開。
3. 絕對不要虛構圖片中看不到的數值。看不清楚的欄位寫「無法辨識」，沒有顯示的資料寫「未提供」。
4. 當只有一張畫面，請勿聲稱看過其他籌碼頁籤或完整歷史行情。

【請依序輸出】
一、圖中可辨識的價格、成交量、日K結構、均線、MACD、RSI（未顯示者註明未提供）。
二、主力買賣超與主力成本（僅在圖片明確顯示時分析）。
三、外資、投信、自營商買賣超的方向及連續性（不可根據單日資料臆測）。
四、券商分點、大戶與散戶籌碼集中度（僅在畫面可見時分析）。
五、看多因素、看空因素、量價背離與潛在轉折。
六、可能的支撐、壓力、進場觀察點、停損失效條件；如果無法推算請說明欠缺哪些資料。
七、依 A 準備起漲 / B 深跌反轉 / C 突發爆量 / D 主力進場 / E DIF 金叉 / F 縮量上漲，逐項標記「符合 / 不符合 / 資料不足」。
八、結論：觀察、等待確認或條件轉弱（不要用保證獲利的語氣）。

所有回答用繁體中文。分數如有使用，明確標註為研究用訊號分數，絕非上漲機率或真實勝率。不得直接代為下單。
""".trimIndent()
    }
    fun forBatchStock(code: String, captureStatus: String): String {
        require(code.matches(Regex("[0-9]{4,6}")))
        return """
請根據以下「使用者授權擷取的籌碼K線多頁截圖」研究股票 $code 的大戶行為與合理觀察進場時機。

【各頁是否確實有截圖及驗證方式（請先逐張檢查）】
$captureStatus

請逐張核對畫面股號、頁籤、資料日期、時間、版面是否重複、是否過期或截到付費牆。
如果有任何圖片未提供、截圖內容與頁面標籤不符、或頁面切換僅透過畫面變動推估，請標示「資料不足／頁面未確認」，禁止自行補造數字。

【七個面向】
1. 日 K 線：5/10/20 日均線、MACD、RSI、量價、是否突破或過熱；未提供不得自行推斷。
2. 籌碼日報：關鍵券商大買、大賣、集中度、買方成本，註明是哪個日期。
3. 法人：外資、投信、自營商實際買賣超及持續性；只有單日就不能稱為連續。
4. 多空：圖片上實際顯示的多空訊號，與股價是否背離。
5. 主力：主力買賣超、成本區、價量是否符合吸籌；避免把主力買超當成必漲。
6. 大戶：大戶和散戶持股/買賣變化，大戶增加而散戶減少是否同步發生。
7. 財報：EPS、月營收、獲利/現金流是否支持行情；圖片沒出現即標未提供。

【輸出格式】
- 圖片內容與可辨識數值：按頁分類，標註資料時間和可信程度。
- 大戶正在做什麼：可能吸籌／可能出貨／互有買賣／無法判斷；各列舉有來源的證據及反證。
- ABCDEF 起漲分類：每項「符合／不符合／資料不足」，列出實際條件。
- 上車時機：只給有條件的進場觀察情境，包含放量/均線/籌碼確認、價位區間、失效停損與風險；缺資料不猜價。
- 行動結論：「優先觀察／等待確認／避免追價／資料不足」。
- 研究用訊號分數（0～100，可省略），明確標示不等於歷史勝率或未來上漲機率。

使用繁體中文。將事實、估計、假設分開。僅供研究，不直接交易、不得保證隔日大漲。
""".trimIndent()
    }
}
